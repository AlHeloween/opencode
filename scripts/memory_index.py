"""The generator for the delegator's memory folder (t127).

`python scripts/memory_index.py <command> <folder> [args]`

  render    <folder>              print the index the files imply
  write     <folder>              write MEMORY.md from the files
  stamp     <folder>              write/refresh the SV block and the canonical name in every file
  baseline  <folder> <out.json>   write the evidence-token manifest (the receipts that must survive)
  links     <folder>              print the link map (target -> file:line)

Every command is idempotent: running it twice over its own output changes
nothing, byte for byte. The index ORDER is the folder's curation and is carried
by the existing index; the CONTENT of every line is generated from the files.
"""

import argparse
import importlib.util
import json
import secrets
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.stderr.reconfigure(encoding="utf-8", errors="replace")

_spec = importlib.util.spec_from_file_location("memory_lib", Path(__file__).resolve().parent / "memory_lib.py")
ml = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ml)
# The MEANING lives in the files' own SV blocks — there is no table here any more
# (t127 memory add 1: the file is the source, the index is the derived copy).

PARENT_GOAL_MD5 = "c7218c11076948a099404504393f1f50"
STEP0 = "project_after_rebuild_2026_10_21.md"

# t124 REPORT.md §7 INDEX: the two files that carry the continuity receipts go
# at the top, right after the STEP 0 pointer, which keeps its place.
PINNED_AFTER_STEP0 = [
    "project_continuity_loss_2026_10_21.md",
    "reference_two_accounts_and_the_session_registry.md",
]

INDEX_MARKER = "<!-- generated by scripts/memory_index.py — do not edit by hand -->"


def topic_files(folder):
    return sorted(p for p in folder.glob("*.md") if p.name != ml.INDEX_NAME)


def load(folder):
    files = topic_files(folder)
    texts = {p.name: ml.read_text(p) for p in files}
    index_path = folder / ml.INDEX_NAME
    index_text = ml.read_text(index_path) if index_path.exists() else ""
    return files, texts, index_text, index_path


def canonical_name_map(texts):
    """target file name -> its canonical `name:`."""
    out = {}
    for fname, text in texts.items():
        fm = ml.parse_frontmatter(text)
        out[fname] = ml.canonical_name(Path(fname).stem)
    return out


def order_for(texts, index_text):
    """The folder's order: STEP 0 first, the pinned files next, then the index's
    own order, then whatever is new — sorted, so the order never depends on a clock."""
    known = set(texts)
    pinned = [f for f in PINNED_AFTER_STEP0 if f in known]
    rest = [t for t in ml.index_order(index_text) if t in known and t != STEP0 and t not in pinned]
    fresh = sorted(known - set(rest) - set(pinned) - {STEP0})
    out = ([STEP0] if STEP0 in known else []) + pinned + rest + fresh
    return out


def entries_for(texts, order):
    """-> [(title, target, summary)] — the title and the rule the delegator acts on.

    The title is the file's OWN (its SV block, the meaning in plain case) and the
    summary is the dominant's RULE clause, so the index line carries what to do; the
    why stays in the file.
    """
    entries = []
    for target in order:
        text = texts[target]
        sv = ml.read_sv(text) or {}
        title = ml.title_for(target, text)
        dominant = sv.get("Semantic dominant", "")
        entries.append((title, target, ml.summary_of(dominant)))
    return entries


def render_index_text(texts, index_text):
    order = order_for(texts, index_text)
    entries = entries_for(texts, order)
    body = ml.render_index(entries)
    return body, order, entries


def cmd_render(args):
    folder = Path(args.folder)
    _, texts, index_text, _ = load(folder)
    body, order, entries = render_index_text(texts, index_text)
    print(body)
    print(f"# {len(entries)} entries | {len(body.encode('utf-8'))} bytes "
          f"(the app loads the first 200 lines / 25 600 bytes)", file=sys.stderr)
    return 0


def cmd_write(args):
    folder = Path(args.folder)
    _, texts, index_text, index_path = load(folder)
    body, order, entries = render_index_text(texts, index_text)
    raw = index_path.read_bytes() if index_path.exists() else b""
    ending = "\r\n" if b"\r\n" in raw else "\n"
    data = (body.replace("\n", ending)).encode("utf-8")
    if data == raw:
        print(f"MEMORY.md unchanged ({len(data)} bytes, {len(entries)} entries)")
        return 0
    index_path.write_bytes(data)
    lines = len(body.splitlines())
    print(f"MEMORY.md written: {len(data)} bytes, {lines} lines, {len(entries)} entries "
          f"(limits: 25600 bytes / 200 lines — headroom {25600 - len(data)} bytes / {200 - lines} lines)")
    return 0


def resolve_link(target, texts):
    """-> the canonical name of the file a link names, or None.

    A link spells its target's `name:`; the spellings that exist in the wild
    are the kebab name, the file's own stem and the underscored name.
    """
    hits = set()
    for f in texts:
        stem = Path(f).stem
        name = ml.canonical_name(stem)
        spellings = {name, stem, name.replace("-", "_")}
        for t in ml.TYPES:
            if name.startswith(t + "-"):
                spellings.add(name[len(t) + 1:])
        if target in spellings:
            hits.add(name)
    return hits.pop() if len(hits) == 1 else None


def stamp_one(path, text, texts, names, labels):
    """-> (new_text, changed, notes) — the SV block, the canonical name, the links.

    The MEANING is never derived here: it is read from the block already in the
    file. A file with no block is left alone and REPORTED — a script cannot write
    the meaning, and the title, the keywords, the dominant and the chain are the
    reader's.
    """
    fname = path.name
    notes = []
    stem = Path(fname).stem
    want_name = ml.canonical_name(stem)
    raw, body = ml.split_frontmatter(text)
    if not raw:
        return text, False, ["no frontmatter — left alone"]
    fm = ml.parse_frontmatter(text)
    changed = False

    if fm.get("name") != want_name:
        new_raw = ml.set_frontmatter_field(raw, "name", want_name)
        text = text.replace(raw, new_raw, 1)
        raw = new_raw
        changed = True
        notes.append(f"name: {fm.get('name')!r} -> {want_name!r}")
    if not fm.get("metadata.node_type"):
        new_raw = ml.set_metadata_field(raw, "node_type", "memory")
        text = text.replace(raw, new_raw, 1)
        raw = new_raw
        changed = True
        notes.append("metadata.node_type filled")
    if not fm.get("metadata.modified"):
        from datetime import datetime, timezone

        mtime = datetime.fromtimestamp(path.stat().st_mtime, tz=timezone.utc)
        new_raw = ml.set_metadata_field(raw, "modified", mtime.isoformat().replace("+00:00", "Z"))
        text = text.replace(raw, new_raw, 1)
        raw = new_raw
        changed = True
        notes.append("metadata.modified filled from the file's own write time")

    # the description is the file's own label — no table overrides it any more.
    for target, _line in ml.scan_links(text):
        canon = resolve_link(target, texts)
        if canon and canon != target:
            text = text.replace(f"[[{target}]]", f"[[{canon}]]")
            changed = True
            notes.append(f"link [[{target}]] -> [[{canon}]]")

    sv = ml.read_sv(text)
    if not sv:
        return text, changed, notes + ["no SV block — the meaning must be written by a reader into the file"]
    md5 = sv.get("md5", "")
    prev = sv.get("prev-md5", ml.ZERO_MD5) or ml.ZERO_MD5
    if not ml.HEX32_RE.match(md5):
        md5 = secrets.token_hex(16)
        prev = sv.get("md5", ml.ZERO_MD5)
        notes.append("md5 was not 32 hex — a fresh label was minted")
    # The MEANING is the file's own: its keywords, its dominant, its title and its
    # chain are read from the block that is already there. Nothing here invents one.
    keywords = ml.sv_keywords(sv.get("Keywords", ""))
    dominant = sv.get("Semantic dominant", "")
    title = sv.get("Title", "")
    parent_md5 = sv.get("parent-goal-md5", PARENT_GOAL_MD5)
    if parent_md5 != PARENT_GOAL_MD5 and parent_md5 not in labels.values():
        parent_md5 = PARENT_GOAL_MD5
        notes.append("parent-goal-md5 is not a label in this folder — the goal md5 was used")
    block = ml.render_sv(dominant, keywords, md5, prev, parent_md5, title)

    if sv and sv["_block"].replace("\r\n", "\n") == block:
        return text, changed, notes
    if sv:
        text = text[: sv["_start"]] + block + text[sv["_end"] :]
    else:
        raw, body = ml.split_frontmatter(text)
        text = raw + "\n" + block + "\n" + body.lstrip("\n")
    changed = True
    return text, changed, notes

def cmd_stamp(args):
    folder = Path(args.folder)
    _, texts, _, _ = load(folder)
    names = canonical_name_map(texts)
    labels = {}
    for fname, text in texts.items():
        sv = ml.read_sv(text)
        if sv and ml.HEX32_RE.match(sv.get("md5", "")):
            labels[fname] = sv["md5"]
    changed = 0
    for fname in sorted(texts):
        new_text, did, notes = stamp_one(folder / fname, texts[fname], texts, names, labels)
        if did:
            path = folder / fname
            ml.write_text(path, new_text)
            changed += 1
            print(f"stamped {fname}: " + "; ".join(notes))
    print(f"{changed} file(s) changed")
    return 0


def cmd_baseline(args):
    folder = Path(args.folder)
    _, texts, index_text, _ = load(folder)
    tokens = set()
    per_file = {}
    for fname, text in texts.items():
        t = ml.body_tokens(text)
        per_file[fname] = sorted(t)
        tokens |= t
    out = {
        "folder": str(folder),
        "files": sorted(texts),
        "tokens": sorted(tokens),
        "per_file": per_file,
    }
    Path(args.out).write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"baseline written: {len(texts)} files, {len(tokens)} distinct evidence tokens -> {args.out}")
    return 0


def cmd_links(args):
    folder = Path(args.folder)
    _, texts, _, _ = load(folder)
    names = canonical_name_map(texts)
    by_name = {v: k for k, v in names.items()}
    unresolved = []
    total = 0
    for fname in sorted(texts):
        for target, line in ml.scan_links(texts[fname]):
            total += 1
            if target not in by_name:
                unresolved.append((fname, line, target))
    print(f"{total} links, {len(unresolved)} unresolved")
    for fname, line, target in unresolved:
        print(f"  {fname}:{line}  [[{target}]]")
    return 0


def main():
    ap = argparse.ArgumentParser(description="generate the delegator's memory index and vectors")
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("render", "write", "stamp", "links"):
        p = sub.add_parser(name)
        p.add_argument("folder")
        p.set_defaults(func=cmd_render if name == "render" else cmd_write if name == "write" else cmd_stamp if name == "stamp" else cmd_links)
    p = sub.add_parser("baseline")
    p.add_argument("folder")
    p.add_argument("out")
    p.set_defaults(func=cmd_baseline)
    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
